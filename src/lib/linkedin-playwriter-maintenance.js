// @ts-check

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const LINKEDIN_PLAYWRITER_MAINTENANCE_MARKER = "__EXO_LINKEDIN_PLAYWRITER_MAINTENANCE__";
const DEFAULT_TIMEOUT_MS = 180000;
const MAX_BUFFER_BYTES = 10 * 1024 * 1024;

/**
 * @param {{
 *   sessionId: string,
 *   playwriterBin: string,
 *   task: any,
 *   timeoutMs?: number | null,
 * }} input
 */
export function runLinkedinMaintenanceWithPlaywriter(input) {
  const timeoutMs = normalizePositiveInteger(input.timeoutMs, DEFAULT_TIMEOUT_MS);
  const outputPath = path.join(
    os.tmpdir(),
    `exo-linkedin-playwriter-maintenance-${Date.now()}-${Math.random().toString(36).slice(2, 10)}.json`,
  );

  try {
    const script = buildLinkedinPlaywriterMaintenanceScript({
      task: input.task,
      outputPath,
    });
    const stdout = execFileSync(input.playwriterBin, [
      "-s",
      input.sessionId,
      "--timeout",
      String(timeoutMs),
      "-e",
      script,
    ], {
      encoding: "utf8",
      maxBuffer: MAX_BUFFER_BYTES,
      env: {
        ...process.env,
        PLAYWRITER_AUTO_ENABLE: "1",
      },
      timeout: timeoutMs + 10000,
    });
    const markerPayload = parsePlaywriterMarkerJson(stdout, LINKEDIN_PLAYWRITER_MAINTENANCE_MARKER);
    const resolvedOutputPath = typeof markerPayload?.outputPath === "string" && markerPayload.outputPath.trim().length
      ? markerPayload.outputPath
      : outputPath;
    if (!fs.existsSync(resolvedOutputPath)) {
      throw new Error(`Playwriter did not materialize LinkedIn maintenance output at ${resolvedOutputPath}.`);
    }
    return JSON.parse(fs.readFileSync(resolvedOutputPath, "utf8"));
  } finally {
    safeUnlink(outputPath);
  }
}

/**
 * @param {{
 *   task: any,
 *   outputPath: string,
 * }} input
 */
export function buildLinkedinPlaywriterMaintenanceScript(input) {
  return [
    "if (state.page && !state.page.isClosed()) {",
    "  await state.page.close().catch(() => {});",
    "}",
    "state.page = await context.newPage();",
    `const task = ${JSON.stringify(input.task)};`,
    `const outputPath = ${JSON.stringify(input.outputPath)};`,
    `const marker = ${JSON.stringify(LINKEDIN_PLAYWRITER_MAINTENANCE_MARKER)};`,
    "const page = state.page;",
    "const wait = (ms) => new Promise((resolve) => setTimeout(resolve, ms));",
    "",
    "async function firstVisible(factories) {",
    "  for (const factory of factories) {",
    "    const locator = factory();",
    "    const count = await locator.count().catch(() => 0);",
    "    for (let index = 0; index < count; index += 1) {",
    "      const candidate = locator.nth(index);",
    "      const visible = await candidate.isVisible().catch(() => false);",
    "      if (visible) return candidate;",
    "    }",
    "  }",
    "  return null;",
    "}",
    "",
    "async function clickFirstVisible(factories, timeout = 12000) {",
    "  const candidate = await firstVisible(factories);",
    "  if (!candidate) return null;",
    "  await candidate.scrollIntoViewIfNeeded().catch(() => {});",
    "  try {",
    "    await candidate.click({ timeout });",
    "  } catch (error) {",
    "    const message = error instanceof Error ? error.message : String(error);",
    "    const clickIntercepted = /intercepts pointer events|locator\\.click: Timeout/i.test(message);",
    "    if (!clickIntercepted) throw error;",
    "    await page.keyboard.press('Escape').catch(() => {});",
    "    await wait(200);",
    "    await candidate.evaluate((node) => {",
    "      node.scrollIntoView({ block: 'center', inline: 'center' });",
    "      if (typeof node.click === 'function') {",
    "        node.click();",
    "        return;",
    "      }",
    "      node.dispatchEvent(new MouseEvent('click', { bubbles: true, cancelable: true, composed: true }));",
    "    });",
    "  }",
    "  return candidate;",
    "}",
    "",
    "async function waitForAnyVisible(factories, timeout = 8000) {",
    "  const deadline = Date.now() + timeout;",
    "  while (Date.now() < deadline) {",
    "    const candidate = await firstVisible(factories);",
    "    if (candidate) return true;",
    "    await wait(250);",
    "  }",
    "  return false;",
    "}",
    "",
    "async function hasVisible(factories) {",
    "  return Boolean(await firstVisible(factories));",
    "}",
    "",
    "function buildBlocked(reason, extra = {}) {",
    "  return {",
    "    status: 'blocked',",
    "    reason,",
    "    action: task.kind || null,",
    "    recipientUrl: task.recipientUrl || null,",
    "    pageUrl: page.url(),",
    "    ...extra,",
    "  };",
    "}",
    "",
    "function buildCompleted(extra = {}) {",
    "  return {",
    "    status: 'completed',",
    "    reason: null,",
    "    action: task.kind || null,",
    "    recipientUrl: task.recipientUrl || null,",
    "    pageUrl: page.url(),",
    "    ...extra,",
    "  };",
    "}",
    "",
    "function messageFactories() {",
    "  return [",
    "    () => page.getByRole('button', { name: /^Message$/i }),",
    "    () => page.locator('button:has-text(\"Message\")'),",
    "    () => page.locator('[role=\"button\"]:has-text(\"Message\")'),",
    "    () => page.getByRole('link', { name: /^Message$/i }),",
    "    () => page.locator('a[href*=\"/messaging/compose\"]:has-text(\"Message\")'),",
    "  ];",
    "}",
    "",
    "function connectFactories() {",
    "  return [",
    "    () => page.getByRole('button', { name: /^Connect$/i }),",
    "    () => page.locator('button:has-text(\"Connect\")'),",
    "    () => page.locator('[role=\"button\"]:has-text(\"Connect\")'),",
    "  ];",
    "}",
    "",
    "function pendingFactories() {",
    "  return [",
    "    () => page.getByRole('button', { name: /^Pending$/i }),",
    "    () => page.locator('button:has-text(\"Pending\")'),",
    "    () => page.locator('[role=\"button\"]:has-text(\"Pending\")'),",
    "  ];",
    "}",
    "",
    "function followFactories() {",
    "  return [",
    "    () => page.getByRole('button', { name: /^Follow$/i }),",
    "    () => page.locator('button:has-text(\"Follow\")'),",
    "    () => page.locator('[role=\"button\"]:has-text(\"Follow\")'),",
    "  ];",
    "}",
    "",
    "function followingFactories() {",
    "  return [",
    "    () => page.getByRole('button', { name: /^Following$/i }),",
    "    () => page.locator('button:has-text(\"Following\")'),",
    "    () => page.locator('[role=\"button\"]:has-text(\"Following\")'),",
    "  ];",
    "}",
    "",
    "function acceptFactories() {",
    "  return [",
    "    () => page.getByRole('button', { name: /^Accept$/i }),",
    "    () => page.locator('button:has-text(\"Accept\")'),",
    "    () => page.locator('[role=\"button\"]:has-text(\"Accept\")'),",
    "  ];",
    "}",
    "",
    "function ignoreFactories() {",
    "  return [",
    "    () => page.getByRole('button', { name: /^(Ignore|Decline)$/i }),",
    "    () => page.locator('button:has-text(\"Ignore\")'),",
    "    () => page.locator('button:has-text(\"Decline\")'),",
    "    () => page.locator('[role=\"button\"]:has-text(\"Ignore\")'),",
    "    () => page.locator('[role=\"button\"]:has-text(\"Decline\")'),",
    "    () => page.getByRole('menuitem', { name: /^(Ignore|Decline)$/i }),",
    "    () => page.locator('[role=\"menuitem\"]:has-text(\"Ignore\")'),",
    "    () => page.locator('[role=\"menuitem\"]:has-text(\"Decline\")'),",
    "  ];",
    "}",
    "",
    "function moreActionsFactories() {",
    "  return [",
    "    () => page.getByRole('button', { name: /^More actions$/i }),",
    "    () => page.getByRole('button', { name: /^More$/i }),",
    "    () => page.locator('button[aria-label*=\"More actions\"]'),",
    "    () => page.locator('button:has-text(\"More\")'),",
    "  ];",
    "}",
    "",
    "function withdrawInvitationFactories() {",
    "  return [",
    "    () => page.getByRole('menuitem', { name: /^Withdraw invitation$/i }),",
    "    () => page.getByRole('button', { name: /^Withdraw invitation$/i }),",
    "    () => page.locator('[role=\"menuitem\"]:has-text(\"Withdraw invitation\")'),",
    "    () => page.locator('[role=\"button\"]:has-text(\"Withdraw invitation\")'),",
    "    () => page.locator('button:has-text(\"Withdraw invitation\")'),",
    "  ];",
    "}",
    "",
    "function withdrawConfirmationFactories() {",
    "  return [",
    "    () => page.getByRole('button', { name: /^Withdraw$/i }),",
    "    () => page.locator('button:has-text(\"Withdraw\")'),",
    "    () => page.locator('[role=\"button\"]:has-text(\"Withdraw\")'),",
    "  ];",
    "}",
    "",
    "function unfollowFactories() {",
    "  return [",
    "    () => page.getByRole('menuitem', { name: /^Unfollow$/i }),",
    "    () => page.getByRole('button', { name: /^Unfollow$/i }),",
    "    () => page.locator('[role=\"menuitem\"]:has-text(\"Unfollow\")'),",
    "    () => page.locator('[role=\"button\"]:has-text(\"Unfollow\")'),",
    "    () => page.locator('button:has-text(\"Unfollow\")'),",
    "  ];",
    "}",
    "",
    "async function gotoRecipientProfile() {",
    "  const profileUrl = typeof task.recipientUrl === 'string' ? task.recipientUrl.trim() : '';",
    "  if (!profileUrl) return buildBlocked('linkedin_maintenance_blocked: recipient profile URL is missing.');",
    "  try {",
    "    await page.goto(profileUrl, { waitUntil: 'domcontentloaded', timeout: 45000 });",
    "  } catch (error) {",
    "    const message = error instanceof Error ? error.message : String(error);",
    "    const aborted = /ERR_ABORTED/i.test(message);",
    "    if (!aborted) throw error;",
    "    const currentUrl = page.url();",
    "    const landedOnProfile = /linkedin\\.com\\/in\\//i.test(currentUrl);",
    "    if (!landedOnProfile) {",
    "      await wait(500);",
    "      await page.goto(profileUrl, { waitUntil: 'domcontentloaded', timeout: 45000 });",
    "    }",
    "  }",
    "  await page.waitForLoadState('domcontentloaded').catch(() => {});",
    "  await waitForAnyVisible([",
    "    () => page.locator(\"main[role='main']\"),",
    "    () => page.locator('main'),",
    "    () => page.locator('body'),",
    "  ], 15000);",
    "  await wait(1000);",
    "  const currentUrl = page.url();",
    "  if (/linkedin\\.com\\/(login|authwall)/i.test(currentUrl)) {",
    "    return buildBlocked(`profile_selection_mismatch: LinkedIn redirected to ${currentUrl}.`);",
    "  }",
    "  return null;",
    "}",
    "",
    "async function captureProfileState() {",
    "  const mainText = await page.locator('main').innerText().catch(async () => await page.locator('body').innerText().catch(() => ''));",
    "  const connectionDegree = /(^|\\s)1st(\\s|$)/i.test(mainText)",
    "    ? 1",
    "    : /(^|\\s)2nd(\\s|$)/i.test(mainText)",
    "      ? 2",
    "      : /(^|\\s)3rd\\+?(\\s|$)/i.test(mainText)",
    "        ? 3",
    "        : null;",
    "  const isOpenProfile = /open profile|free to message|open to message/i.test(mainText);",
    "  return {",
    "    connectionDegree,",
    "    isOpenProfile,",
    "    hasMessage: await hasVisible(messageFactories()),",
    "    hasConnect: await hasVisible(connectFactories()),",
    "    hasPending: await hasVisible(pendingFactories()),",
    "    hasFollow: await hasVisible(followFactories()),",
    "    hasFollowing: await hasVisible(followingFactories()),",
    "    hasAccept: await hasVisible(acceptFactories()),",
    "    hasIgnore: await hasVisible(ignoreFactories()),",
    "  };",
    "}",
    "",
    "async function openMoreActions() {",
    "  return clickFirstVisible(moreActionsFactories(), 10000);",
    "}",
    "",
    "async function maybeConfirm(factories, timeout = 5000) {",
    "  const visible = await waitForAnyVisible(factories, timeout);",
    "  if (!visible) return false;",
    "  const clicked = await clickFirstVisible(factories, timeout);",
    "  return Boolean(clicked);",
    "}",
    "",
    "async function performWithdrawConnection() {",
    "  const gotoFailure = await gotoRecipientProfile();",
    "  if (gotoFailure) return gotoFailure;",
    "  const state = await captureProfileState();",
    "  if (state.hasMessage || state.connectionDegree === 1 || state.isOpenProfile) {",
    "    return buildBlocked('linkedin_withdraw_connection_blocked: profile is already messageable or connected.', { profileSnapshot: state });",
    "  }",
    "  if (!state.hasPending && state.hasConnect) {",
    "    return buildCompleted({ alreadySatisfied: true, profileSnapshot: state });",
    "  }",
    "  let clickedWithdraw = false;",
    "  if (state.hasPending) {",
    "    const pending = await clickFirstVisible(pendingFactories(), 10000);",
    "    if (pending) {",
    "      await wait(500);",
    "      const withdraw = await clickFirstVisible(withdrawInvitationFactories(), 10000);",
    "      clickedWithdraw = Boolean(withdraw);",
    "    }",
    "  }",
    "  if (!clickedWithdraw) {",
    "    const more = await openMoreActions();",
    "    if (more) {",
    "      await wait(500);",
    "      const withdraw = await clickFirstVisible(withdrawInvitationFactories(), 10000);",
    "      clickedWithdraw = Boolean(withdraw);",
    "    }",
    "  }",
    "  if (!clickedWithdraw) {",
    "    return buildBlocked('linkedin_withdraw_connection_blocked: LinkedIn did not expose a withdraw-invitation action on the profile.', { profileSnapshot: state });",
    "  }",
    "  await wait(400);",
    "  await maybeConfirm(withdrawConfirmationFactories(), 5000);",
    "  const confirmed = await waitForAnyVisible([",
    "    ...connectFactories(),",
    "    () => page.getByText(/Invitation withdrawn/i),",
    "    () => page.locator('text=/Invitation withdrawn/i'),",
    "  ], 10000);",
    "  if (!confirmed) {",
    "    return buildBlocked('linkedin_withdraw_connection_unconfirmed: LinkedIn did not confirm that the invitation was withdrawn.');",
    "  }",
    "  return buildCompleted();",
    "}",
    "",
    "async function performRejectConnectionRequest() {",
    "  const gotoFailure = await gotoRecipientProfile();",
    "  if (gotoFailure) return gotoFailure;",
    "  const state = await captureProfileState();",
    "  let ignored = await clickFirstVisible(ignoreFactories(), 10000);",
    "  if (!ignored) {",
    "    const more = await openMoreActions();",
    "    if (more) {",
    "      await wait(500);",
    "      ignored = await clickFirstVisible(ignoreFactories(), 10000);",
    "    }",
    "  }",
    "  if (!ignored) {",
    "    return buildBlocked('linkedin_reject_connection_request_blocked: LinkedIn did not expose an Ignore or Decline action on the profile.', { profileSnapshot: state });",
    "  }",
    "  await wait(400);",
    "  await maybeConfirm(ignoreFactories(), 4000);",
    "  const confirmed = await waitForAnyVisible([",
    "    ...connectFactories(),",
    "    () => page.getByText(/Invitation ignored|Ignored invitation|Invitation declined|Declined/i),",
    "    () => page.locator('text=/Invitation ignored|Ignored invitation|Invitation declined|Declined/i'),",
    "  ], 10000);",
    "  if (!confirmed) {",
    "    return buildBlocked('linkedin_reject_connection_request_unconfirmed: LinkedIn did not confirm that the invitation was ignored.', { profileSnapshot: state });",
    "  }",
    "  return buildCompleted();",
    "}",
    "",
    "async function performUnfollowProfile() {",
    "  const gotoFailure = await gotoRecipientProfile();",
    "  if (gotoFailure) return gotoFailure;",
    "  const initialState = await captureProfileState();",
    "  if (initialState.hasFollow && !initialState.hasFollowing) {",
    "    return buildCompleted({ alreadySatisfied: true, profileSnapshot: initialState });",
    "  }",
    "  let clickedUnfollow = false;",
    "  if (initialState.hasFollowing) {",
    "    const following = await clickFirstVisible(followingFactories(), 10000);",
    "    if (following) {",
    "      await wait(500);",
    "      const unfollow = await clickFirstVisible(unfollowFactories(), 10000);",
    "      clickedUnfollow = Boolean(unfollow);",
    "    }",
    "  }",
    "  if (!clickedUnfollow) {",
    "    const more = await openMoreActions();",
    "    if (more) {",
    "      await wait(500);",
    "      const unfollow = await clickFirstVisible(unfollowFactories(), 10000);",
    "      clickedUnfollow = Boolean(unfollow);",
    "    }",
    "  }",
    "  if (!clickedUnfollow) {",
    "    return buildBlocked('linkedin_unfollow_blocked: LinkedIn did not expose an unfollow action on the profile.', { profileSnapshot: initialState });",
    "  }",
    "  await wait(400);",
    "  await maybeConfirm(unfollowFactories(), 4000);",
    "  const confirmed = await waitForAnyVisible([",
    "    ...followFactories(),",
    "    () => page.getByText(/Unfollowed/i),",
    "    () => page.locator('text=/Unfollowed/i'),",
    "  ], 10000);",
    "  if (!confirmed) {",
    "    return buildBlocked('linkedin_unfollow_unconfirmed: LinkedIn did not confirm the unfollow action.', { profileSnapshot: initialState });",
    "  }",
    "  return buildCompleted();",
    "}",
    "",
    "let result;",
    "try {",
    "  result = task.kind === 'withdraw_connection'",
    "    ? await performWithdrawConnection()",
    "    : task.kind === 'reject_connection_request'",
    "      ? await performRejectConnectionRequest()",
    "      : await performUnfollowProfile();",
    "} catch (error) {",
    "  result = buildBlocked(`playwriter_maintenance_failed: ${error instanceof Error ? error.message : String(error)}`);",
    "}",
    "require('node:fs').writeFileSync(outputPath, JSON.stringify(result));",
    "console.log(marker + JSON.stringify({ outputPath }));",
  ].join("\n");
}

/**
 * @param {string} stdout
 * @param {string} marker
 */
function parsePlaywriterMarkerJson(stdout, marker) {
  const line = String(stdout ?? "")
    .split("\n")
    .find((candidate) => candidate.includes(marker));
  if (!line) {
    throw new Error(`Playwriter output did not include ${marker}.`);
  }
  const start = line.indexOf(marker);
  const jsonText = line.slice(start + marker.length).trim();
  return JSON.parse(jsonText);
}

/**
 * @param {string} filePath
 */
function safeUnlink(filePath) {
  try {
    fs.unlinkSync(filePath);
  } catch (_error) {
    // Best-effort cleanup only.
  }
}

/**
 * @param {number | string | null | undefined} raw
 * @param {number} fallback
 */
function normalizePositiveInteger(raw, fallback) {
  const parsed = Number(raw);
  return Number.isFinite(parsed) && parsed > 0 ? Math.floor(parsed) : fallback;
}
