    "  return clickFirstVisible([",
    "    () => page.getByRole('button', { name: /^More actions$/i }),",
    "    () => page.getByRole('button', { name: /^More$/i }),",
    "    () => page.locator('button[aria-label*=\"More actions\"]'),",
    "    () => page.locator('button:has-text(\"More\")'),",
