    "    () => page.getByRole('menuitem', { name: /^Connect$/i }),",
    "    () => page.getByRole('button', { name: /^Connect$/i }),",
    "    () => page.locator('[role=\"menuitem\"]:has-text(\"Connect\")'),",
    "    () => page.locator('[role=\"button\"]:has-text(\"Connect\")'),",
    "  ], 10000);",
    "  if (!menuConnect) return { ok: false, reason: 'linkedin_connection_request_blocked: Connect was not available in more actions.' };",
    "  return { ok: true, from: 'more_actions' };",
    "}",
    "",
    "async function sendConnectionRequest() {",
    "  const note = typeof handoff.message === 'string' ? handoff.message.trim() : '';",
    "  if (note.length > 300) {",
    "    return buildBlocked(`linkedin_connection_request_blocked: note length ${note.length} exceeds LinkedIn's 300 character limit.`);",
    "  }",
    "  const gotoFailure = await gotoRecipientProfile();",
    "  if (gotoFailure) return gotoFailure;",
    "  const profileSnapshot = await captureProfileState();",
    "",
    "  const connectFlow = await openConnectFlow(profileSnapshot);",
    "  if (!connectFlow.ok) return buildBlocked(connectFlow.reason, connectFlow.profileSnapshot ? { profileSnapshot: connectFlow.profileSnapshot } : {});",
    "  await wait(900);",
    "",
    "  if (note.length) {",
    "    const addNote = await clickFirstVisible([",
    "      () => page.getByRole('button', { name: /^Add a note$/i }),",
    "      () => page.locator('button:has-text(\"Add a note\")'),",
    "    ], 6000);",
    "    if (addNote) await wait(400);",
    "    const noteBox = await firstVisible([",
    "      () => page.getByRole('textbox'),",
    "      () => page.locator('textarea'),",
    "    ]);",
    "    if (!noteBox) return buildBlocked('linkedin_connection_request_blocked: LinkedIn did not expose a note field for this invitation.');",
    "    await noteBox.fill(note);",
    "  }",
    "",
    "  if (dryRun) {",
    "    return {",
    "      status: 'ready_to_send',",
    "      reason: null,",
    "      action: handoff.action || null,",
    "      surface: handoff.surface || null,",
    "      recipientUrl: handoff.recipient?.profileUrl || null,",
    "      pageUrl: page.url(),",
    "    };",
    "  }",
    "",
    "  const sendButton = await clickFirstVisible([",
    "    () => page.getByRole('button', { name: /^(Send|Send now|Send without a note)$/i }),",
    "    () => page.locator('button:has-text(\"Send\")'),",
    "  ], 10000);",
    "  if (!sendButton) return buildBlocked('linkedin_connection_request_blocked: LinkedIn did not expose a send button for the invitation dialog.');",
    "",
    "  const confirmed = await waitForAnyVisible([",
    "    () => page.getByRole('button', { name: /^(Pending|Sent)$/i }),",
    "    () => page.locator('button:has-text(\"Pending\")'),",
