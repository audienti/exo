    "  await waitForPrimaryProfileActions(6000).catch(() => false);",
    "  const directConnect = await clickFirstVisible([",
    "    () => page.getByRole('button', { name: /^Connect$/i }),",
    "    () => page.locator('button:has-text(\"Connect\")'),",
    "    () => page.locator('[role=\"button\"]:has-text(\"Connect\")'),",
    "  ], 10000);",
    "  if (directConnect) return { ok: true, from: 'direct' };",
    "",
    "  const pending = await firstVisible([",
    "    () => page.getByRole('button', { name: /^Pending$/i }),",
    "    () => page.locator('button:has-text(\"Pending\")'),",
    "  ]);",
    "  if (pending) return { ok: false, reason: 'linkedin_connection_request_blocked: invitation is already pending.' };",
    "",
