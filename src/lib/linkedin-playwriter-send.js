// @ts-check

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const LINKEDIN_PLAYWRITER_SEND_MARKER = "__EXO_LINKEDIN_PLAYWRITER_SEND__";
const DEFAULT_TIMEOUT_MS = 180000;
const MAX_BUFFER_BYTES = 10 * 1024 * 1024;

/**
 * @param {{
 *   sessionId: string,
 *   playwriterBin: string,
 *   handoff: any,
 *   dryRun?: boolean | null,
 *   timeoutMs?: number | null,
 * }} input
 */
export function sendLinkedinMessageWithPlaywriter(input) {
  const timeoutMs = normalizePositiveInteger(input.timeoutMs, DEFAULT_TIMEOUT_MS);
  const outputPath = path.join(
    os.tmpdir(),
    `exo-linkedin-playwriter-send-${Date.now()}-${Math.random().toString(36).slice(2, 10)}.json`,
  );

  try {
    const script = buildLinkedinPlaywriterSendScript({
      handoff: input.handoff,
      outputPath,
      dryRun: input.dryRun === true,
    });
    const stdout = execFileSync(input.playwriterBin, [
      "-s",
      input.sessionId,
      "--timeout",
      String(timeoutMs),
      "-e",
      script,
    ], {
      encoding: "utf8",
      maxBuffer: MAX_BUFFER_BYTES,
      env: {
        ...process.env,
        PLAYWRITER_AUTO_ENABLE: "1",
      },
      timeout: timeoutMs + 10000,
    });
    const markerPayload = parsePlaywriterMarkerJson(stdout, LINKEDIN_PLAYWRITER_SEND_MARKER);
    const resolvedOutputPath = typeof markerPayload?.outputPath === "string" && markerPayload.outputPath.trim().length
      ? markerPayload.outputPath
      : outputPath;
    if (!fs.existsSync(resolvedOutputPath)) {
      throw new Error(`Playwriter did not materialize LinkedIn send output at ${resolvedOutputPath}.`);
    }
    return JSON.parse(fs.readFileSync(resolvedOutputPath, "utf8"));
  } finally {
    safeUnlink(outputPath);
  }
}

