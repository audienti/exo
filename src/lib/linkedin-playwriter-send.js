    "async function focusComposer(locator) {",
    "  await dismissComposerTypeahead();",
    "  await locator.focus().catch(() => {});",
    "  const focused = await locator.evaluate((node) => {",
    "    const active = document.activeElement;",
    "    return active === node || (active instanceof HTMLElement && node instanceof HTMLElement && node.contains(active));",
    "  }).catch(() => false);",
    "  if (focused) return true;",
    "  await locator.evaluate((node) => {",
    "    if (node instanceof HTMLElement) {",
    "      node.focus();",
    "    }",
    "  }).catch(() => {});",
    "  await wait(120);",
    "  return await locator.evaluate((node) => {",
    "    const active = document.activeElement;",
    "    return active === node || (active instanceof HTMLElement && node instanceof HTMLElement && node.contains(active));",
    "  }).catch(() => false);",
    "}",
    "",
    "async function clearComposer(locator) {",
    "  const isNativeInput = await locator.evaluate((node) => node instanceof HTMLTextAreaElement || node instanceof HTMLInputElement).catch(() => false);",
    "  if (isNativeInput) {",
    "    await locator.fill('');",
    "    return true;",
    "  }",
    "  await focusComposer(locator).catch(() => false);",
    "  await locator.evaluate((node) => {",
    "    if (!(node instanceof HTMLElement)) return false;",
    "    node.innerHTML = '';",
    "    const selection = window.getSelection();",
    "    if (selection) {",
    "      const range = document.createRange();",
    "      range.selectNodeContents(node);",
    "      range.collapse(true);",
    "      selection.removeAllRanges();",
    "      selection.addRange(range);",
    "    }",
    "    node.dispatchEvent(new InputEvent('input', { bubbles: true, inputType: 'deleteContentBackward', data: null }));",
    "    node.dispatchEvent(new Event('change', { bubbles: true }));",
    "    return true;",
    "  }).catch(() => false);",
    "  await wait(100);",
    "  return true;",
    "}",
